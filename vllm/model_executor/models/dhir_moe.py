"""Inference-only Dhir 5B MoE.

The attention block is Dhir 2B's. Every layer's feed-forward block is a mixture of experts: a softmax router over
all experts keeps the top-k, renormalises their weights when `norm_topk_prob` is set, and sums their SwiGLU outputs.
There are no shared experts.
"""

